import java.nio.file.*;
import java.util.*;

/**
 * Generates the quick bar icons (app/src/main/res/drawable/{wifi_*,ftp_*,quick_*}.xml) in two
 * styles, framed and line, from one set of 24x24 symbols, so every icon has the same stroke.
 * Run from the repository root:
 *   java tools/GenQuickIcons.java app/src/main/res/drawable
 */
public class GenQuickIcons {
  static final double W = 2.75; // stroke, in units of the 48x48 viewport, the same in every icon

  static String circle(double cx, double cy, double r) {
    return String.format(Locale.US, "M%.2f,%.2f A%.2f,%.2f 0 1 0 %.2f,%.2f A%.2f,%.2f 0 1 0 %.2f,%.2f Z",
        cx - r, cy, r, r, cx + r, cy, r, r, cx - r, cy);
  }

  // Each glyph: list of {"s"|"f"|"k", pathData}: stroke, fill, knockout slash.
  static final double WY = 18.5; // Wi-Fi centre: the fan spreads upwards from it

  static String arc(double r) {
    double d = r * Math.sqrt(0.5);
    return String.format(Locale.US, "M%.2f,%.2f A%.2f,%.2f 0 0 1 %.2f,%.2f", 12 - d, WY - d, r, r, 12 + d, WY - d);
  }

  static Map<String, List<String[]>> glyphs = new LinkedHashMap<>();
  static void g(String name, String[]... parts) { glyphs.put(name, Arrays.asList(parts)); }

  public static void main(String[] a) throws Exception {
    String arcs = arc(4.5) + " " + arc(9) + " " + arc(13.5);
    String[] dot = {"f", circle(12, WY, 1.9)};
    String slash = "M4,4 L20,20";
    String arrows = "M8,19.5 V4.5 M4,8.5 L8,4.5 L12,8.5 M16,4.5 V19.5 M12,15.5 L16,19.5 L20,15.5";
    g("wifi_on", new String[]{"s", arcs}, dot);
    g("wifi_off", new String[]{"s", arcs}, dot, new String[]{"k", slash});
    g("ftp_on", new String[]{"s", arrows});
    g("ftp_off", new String[]{"s", arrows}, new String[]{"k", slash});
    StringBuilder rays = new StringBuilder();
    for (int i = 0; i < 8; i++) {
      double t = Math.toRadians(i * 45);
      rays.append(String.format(Locale.US, "M%.2f,%.2f L%.2f,%.2f ", 12 + 7 * Math.cos(t), 12 + 7 * Math.sin(t),
          12 + 10 * Math.cos(t), 12 + 10 * Math.sin(t)));
    }
    g("quick_brightness", new String[]{"s", circle(12, 12, 4.25) + " " + rays.toString().trim()});
    g("quick_contrast", new String[]{"s", circle(12, 12, 9)}, new String[]{"f", "M12,3 A9,9 0 0 1 12,21 Z"});
    g("quick_clean", new String[]{"s", "M12,2.5 V10.5 M8,10.5 H16 V14.5 H8 Z M8,14.5 L5.5,21.5 H18.5 L16,14.5 M10,17.5 L9.5,21.5 M14,17.5 L14.5,21.5"});
    g("quick_lock", new String[]{"s", "M7,10.5 H17 A2,2 0 0 1 19,12.5 V19 A2,2 0 0 1 17,21 H7 A2,2 0 0 1 5,19 V12.5 A2,2 0 0 1 7,10.5 Z M8.5,10.5 V7.5 A3.5,3.5 0 0 1 15.5,7.5 V10.5 M12,15 V17.5"},
        new String[]{"f", circle(12, 15, 1.3)});

    StringBuilder gear = new StringBuilder();
    int teeth = 8;
    double step = 2 * Math.PI / teeth;
    for (int i = 0; i < teeth; i++) {
      double m = i * step - Math.PI / 2;
      double[][] pts = {{7.4, m - step * 0.30}, {10, m - step * 0.17}, {10, m + step * 0.17}, {7.4, m + step * 0.30}};
      for (int k = 0; k < pts.length; k++) {
        gear.append(String.format(Locale.US, "%s%.2f,%.2f ", i == 0 && k == 0 ? "M" : "L",
            12 + pts[k][0] * Math.cos(pts[k][1]), 12 + pts[k][0] * Math.sin(pts[k][1])));
      }
    }
    g("quick_settings", new String[]{"s", gear.append("Z ").append(circle(12, 12, 3)).toString()});

    Path out = Paths.get(a[0]);
    for (Map.Entry<String, List<String[]>> e : glyphs.entrySet()) {
      Files.write(out.resolve(e.getKey() + ".xml"), icon(e.getKey(), e.getValue(), true).getBytes("UTF-8"));
      Files.write(out.resolve(e.getKey() + "_line.xml"), icon(e.getKey(), e.getValue(), false).getBytes("UTF-8"));
    }
  }

  static String icon(String name, List<String[]> parts, boolean framed) {
    double scale = framed ? 1.3 : 1.65;
    double shift = 24 - 12 * scale;
    double w = W / scale;
    StringBuilder x = new StringBuilder();
    x.append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
    x.append("<!-- Generated by tools/GenQuickIcons.java (").append(framed ? "framed" : "line").append(" style): same stroke in every icon. -->\n");
    x.append("<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n");
    x.append("    android:width=\"40dp\"\n    android:height=\"40dp\"\n");
    x.append("    android:viewportWidth=\"48\"\n    android:viewportHeight=\"48\">\n");
    if (framed) {
      double i = W / 2 + 0.6;
      double r = 8;
      x.append(path(String.format(Locale.US, "M%.2f,%.2f H%.2f A%.0f,%.0f 0 0 1 %.2f,%.2f V%.2f A%.0f,%.0f 0 0 1 %.2f,%.2f H%.2f A%.0f,%.0f 0 0 1 %.2f,%.2f V%.2f A%.0f,%.0f 0 0 1 %.2f,%.2f Z",
          i + r, i, 48 - i - r, r, r, 48 - i, i + r, 48 - i - r, r, r, 48 - i - r, 48 - i, i + r, r, r, i, 48 - i - r, i + r, r, r, i + r, i),
          "s", W, "    "));
    }
    x.append(String.format(Locale.US, "    <group\n        android:scaleX=\"%.3f\"\n        android:scaleY=\"%.3f\"\n        android:translateX=\"%.2f\"\n        android:translateY=\"%.2f\">\n",
        scale, scale, shift, shift));
    for (String[] p : parts) {
      if (p[0].equals("k")) {
        // White gap around the slash, then the slash.
        x.append(path(p[1], "white", w + 2.4 / scale, "        "));
      }
      x.append(path(p[1], p[0], w, "        "));
    }
    x.append("    </group>\n</vector>\n");
    return x.toString();
  }

  static String path(String d, String kind, double w, String ind) {
    StringBuilder x = new StringBuilder(ind + "<path\n");
    x.append(ind).append("    android:pathData=\"").append(d).append("\"");
    if (kind.equals("f")) {
      x.append("\n").append(ind).append("    android:fillColor=\"#000000\"");
    } else {
      String color = kind.equals("white") ? "#FFFFFF" : "#000000";
      x.append("\n").append(ind).append("    android:strokeColor=\"").append(color).append("\"");
      x.append(String.format(Locale.US, "\n%s    android:strokeWidth=\"%.2f\"", ind, w));
      x.append("\n").append(ind).append("    android:strokeLineCap=\"round\"");
      x.append("\n").append(ind).append("    android:strokeLineJoin=\"round\"");
    }
    return x.append(" />\n").toString();
  }
}
